#!/usr/bin/env bash
# Shared provisioning helpers.

# Print an actionable notice only when the guest OS reports that a reboot is
# required (for example, after a kernel or core-library update). Provisioning
# itself is not interrupted, and services configured by the lab are started
# immediately.
report_reboot_requirement() {
    if [ -f /var/run/reboot-required ]; then
        echo
        echo "NT2102: guest reboot required to finish OS updates."
        echo "Run from the host: vagrant reload \"${HOSTNAME%%.*}\""
        if [ -s /var/run/reboot-required.pkgs ]; then
            echo "Packages requesting reboot: $(tr '\n' ' ' < /var/run/reboot-required.pkgs)"
        fi
    fi
}

# install_lab_routes "CIDR via GATEWAY" ...
# Installs a systemd oneshot service that (re)adds lab routes on every boot.
install_lab_routes() {
    local unit=/etc/systemd/system/lab-routes.service
    local script=/usr/local/sbin/lab-routes.sh

    cat > "$script" <<'EOF'
#!/usr/bin/env bash
# Auto-generated by provisioning. Adds persistent lab routes.
set -eu
EOF
    for spec in "$@"; do
        echo "ip route replace $spec || true" >> "$script"
    done
    chmod +x "$script"

    cat > "$unit" <<'EOF'
[Unit]
Description=NT2102 lab persistent routes
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=/usr/local/sbin/lab-routes.sh
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF

    systemctl daemon-reload
    systemctl enable --now lab-routes.service
}

# mount_data_disk [mountpoint]
# Finds the dedicated 2nd disk (attached at SATA port 2 by the Vagrantfile),
# formats it ext4 the first time, and mounts it at MOUNTPOINT (default /data).
# On subsequent boots the fstab entry mounts it automatically.
mount_data_disk() {
    local mp="${1:-/data}"

    mkdir -p "$mp"

    # If already mounted (subsequent provisions), we are done.
    if mountpoint -q "$mp"; then
        return 0
    fi

    # Identify the data disk: an unpartitioned, unmounted block device that
    # isn't the root disk. This avoids hard-coding /dev/sdb (which shifts
    # depending on whether the box has a config disk on port 1).
    local root_disk
    root_disk="$(lsblk -no PKNAME "$(findmnt -no SOURCE /)" | head -n1 || true)"

    local disk
    disk="$(lsblk -dno NAME,TYPE,MOUNTPOINT | awk -v root="$root_disk" '
        $2 == "disk" && $3 == "" && $1 != root { print $1; exit }
    ')"

    if [ -z "$disk" ]; then
        echo "mount_data_disk: no candidate data disk found" >&2
        lsblk >&2
        return 1
    fi

    local dev="/dev/${disk}"

    # Format only if it has no filesystem yet.
    if ! blkid "$dev" >/dev/null 2>&1; then
        mkfs.ext4 -q -F -L nt2102-data "$dev"
    fi

    local uuid
    uuid="$(blkid -s UUID -o value "$dev")"

    # Persist mount via /etc/fstab (idempotent: replace any existing entry for this mp).
    sed -i "\|[[:space:]]${mp}[[:space:]]|d" /etc/fstab
    echo "UUID=${uuid}  ${mp}  ext4  defaults,nofail  0  2" >> /etc/fstab
    mount "$mp"
    chown vagrant:vagrant "$mp" || true
}
